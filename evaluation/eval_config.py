"""
evaluation/eval_config.py  -- Phase 9 configuration.

All values are env-driven. Override via .env or shell exports.
"""
import os
from dotenv import load_dotenv

load_dotenv()

# ── Groq (reused as the RAGAS judge LLM) ─────────────────────────────
GROQ_API_KEY            = os.getenv("GROQ_API_KEY")
# Use a fast, reliable model as the RAGAS judge.
# openai/gpt-oss-120b is the generation model; use llama-3.3-70b for judging.
EVAL_JUDGE_MODEL        = os.getenv("EVAL_JUDGE_MODEL", "llama-3.3-70b-versatile")

# ── RAG pipeline parameters used during evaluation runs ──────────────
EVAL_TOP_K              = int(os.getenv("EVAL_TOP_K",       "20"))
EVAL_RERANK_TOP_K       = int(os.getenv("EVAL_RERANK_TOP_K", "5"))
EVAL_MIN_SCORE          = float(os.getenv("EVAL_MIN_SCORE",  "0.3"))

# ── File paths ────────────────────────────────────────────────────────
# Input dataset (generated by Phase 8 -- lives in evaluation_data/ as source data)
EVAL_DATASET_PATH       = os.getenv("EVAL_DATASET_PATH",    "evaluation_data/eval_dataset.json")

# Evaluation outputs (all go into evaluation_reports/ -- dedicated reports folder)
EVAL_RESULTS_RAW_PATH   = os.getenv("EVAL_RESULTS_RAW_PATH","evaluation_reports/eval_results_raw.json")
EVAL_RESULTS_SCORES_PATH= os.getenv("EVAL_RESULTS_SCORES",  "evaluation_reports/eval_scores.csv")
EVAL_REPORT_PATH        = os.getenv("EVAL_REPORT_PATH",     "evaluation_reports/evaluation_report.md")

# ── Runner knobs ──────────────────────────────────────────────────────
# How many seconds to wait between pipeline calls to avoid Groq rate limits.
EVAL_REQUEST_DELAY_SEC  = float(os.getenv("EVAL_REQUEST_DELAY_SEC", "1.0"))
